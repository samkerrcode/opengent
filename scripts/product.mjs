// Generates frontend and Tauri identity artifacts from product.json.
// product.json is the single source of truth; Rust reads it at build time (crates/agent-core/build.rs).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const product = JSON.parse(readFileSync(resolve(root, "product.json"), "utf8"));

const rules = {
  displayName: /^[^\s].{0,63}$/,
  slug: /^[a-z][a-z0-9-]{1,31}$/,
  dataDirName: /^\.[a-z][a-z0-9-]{1,31}$/,
  identifier: /^[a-zA-Z][a-zA-Z0-9-]*(\.[a-zA-Z][a-zA-Z0-9-]*){1,}$/,
  version: /^\d+\.\d+\.\d+$/,
  description: /^.{1,200}$/,
};
for (const [key, rule] of Object.entries(rules)) {
  const value = product[key];
  if (typeof value !== "string" || !rule.test(value)) {
    console.error(`product.json: invalid "${key}": ${JSON.stringify(value)}`);
    process.exit(1);
  }
}

const tsOut = resolve(root, "src/lib/generated/product.ts");
mkdirSync(dirname(tsOut), { recursive: true });
writeFileSync(
  tsOut,
  `// Generated by scripts/product.mjs from product.json. Do not edit.\n` +
    `export const product = ${JSON.stringify(
      {
        displayName: product.displayName,
        slug: product.slug,
        version: product.version,
        description: product.description,
      },
      null,
      2,
    )} as const;\n`,
);

// Tauri config overlay (merged over src-tauri/tauri.conf.json via `--config`).
// The merge is JSON Merge Patch (RFC 7396): arrays are replaced wholesale, so the
// overlay's windows array must carry every window property, not just the overrides.
const baseConfig = JSON.parse(readFileSync(resolve(root, "src-tauri/tauri.conf.json"), "utf8"));
const baseWindows = baseConfig.app?.windows ?? [{ label: "main" }];
const windows = baseWindows.map((w) => ({ ...w, title: product.displayName }));

const tauriOut = resolve(root, "src-tauri/tauri.product.conf.json");
writeFileSync(
  tauriOut,
  JSON.stringify(
    {
      productName: product.displayName,
      version: product.version,
      identifier: product.identifier,
      app: { windows },
      bundle: { shortDescription: product.description },
    },
    null,
    2,
  ) + "\n",
);

console.log(`product: ${product.displayName} v${product.version} (${product.identifier})`);
